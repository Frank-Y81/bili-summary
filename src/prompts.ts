export const COMMON_CONSTRAINTS =
  `先整体理解视频，再根据当前模式进行处理。
关注视频的主题、主线、内容之间的关系，以及作者/创作者的表达与意图，而不是机械复述字幕。
可以基于视频内容进行合理的归纳、解释和解读，但不要把自己的推测或补充说成视频中的内容。
对于输入中没有提供或无法确定的信息，不要自行补全或假装知道。`
