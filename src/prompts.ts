// === prompt 模式系统 ===
// 目标：通用约束（内置不可改）+ 用户自定义模式（命名 + 自写指令）
// 第 1 步：只定义数据结构和内置常量，不影响现有功能

// 用户模式
export interface PromptMode {
  id: string
  name: string
  prompt: string
  createdAt: number
}

// 模式上限（含默认模式）
export const MAX_MODES = 6

// 内置默认模式的固定 id
export const DEFAULT_MODE_ID = 'default-general'

// 创建内置默认模式（不可删除）
export function createDefaultMode(): PromptMode {
  return {
    id: DEFAULT_MODE_ID,
    name: '通用笔记',
    prompt: '请返回您反复阅读正文后精心写成的笔记，默认使用中文。不要问候，直接开始。',
    createdAt: 0
  }
}

// === 长字幕分片汇总之用（只在字幕超阈值时才走，见 subtitle-split.ts）===

// 第一轮（map）：每片先压成要点，作为第二轮的输入
// 不掺用户模式的话，模式关心的细节会被通用压缩丢掉；掺了又要防止它把每片都写成完整文章，所以两条都说清
export const MAP_INSTRUCTION =
  `这是同一个视频字幕的其中一段。本轮只做一件事：把这一段里值得留下的信息压成要点。
只输出要点列表，不要写成文章、不要写成笔记体、不要问候、不要分段叙述。
整段控制在 500 字以内（后面还要把各段要点合并成篇，太长会拖垮第二步）。
信息密度优先：人名、概念、数字、结论、例子都要留，寒暄与口头语丢掉；条目之间不要重复。
如果这一段里确实没有实质内容（开场、闲聊、过渡），就只回一行：（本段无实质内容）。

以下是本次要关注的重点，抽要点时优先保留与它相关的内容：`

// 第二轮（reduce）：把各片要点合成最终总结
// 合并的活先干完，再按用户模式成文 —— 所以这条指令摆在模式指令前面
export const REDUCE_INSTRUCTION =
  `下面是同一个视频各段分别抽出的要点，按时间顺序排列。请先在心里把它们合成一份整体理解再动笔：
合并重复的要点、理顺它们之间的关系，不要按“第几段”分段罗列，也不要新增要点里没有出现过的结论。

然后再按下面的要求输出最终结果：`

// === 内置通用片段（用户不可见、不可改）===

